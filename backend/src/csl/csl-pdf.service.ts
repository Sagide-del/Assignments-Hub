import { cslToday } from "./csl.dto";
import { Injectable, ServiceUnavailableException } from "@nestjs/common";
import { ConfigService } from "@nestjs/config";
import puppeteer from "puppeteer-core";
import chromium from "@sparticuz/chromium";
import { CslPhotoService } from "./csl-photo.service";
export const escapeHtml = (v: unknown) =>
  String(v ?? "").replace(
    /[&<>"']/g,
    (c) =>
      ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[
        c
      ]!,
  );
@Injectable()
export class CslPdfService {
  private busy = false;
  constructor(
    private readonly photos: CslPhotoService,
    private readonly config: ConfigService,
  ) {}
  async render(data: any) {
    if (this.busy)
      throw new ServiceUnavailableException(
        "Another logbook is rendering. Please retry shortly.",
      );
    if (data.logs.length > 500)
      throw new ServiceUnavailableException(
        "This logbook requires an extended export. Contact your school administrator.",
      );
    this.busy = true;
    let browser;
    try {
      const cards = [];
      let photoBytes = 0;
      for (const log of data.logs) {
        let photo = "";
        if (log.photo_url) {
          const bytes = await this.photos.image(
            log.photo_url,
            log.school_id,
            log.student_id,
          );
          photoBytes += bytes.length;
          if (photoBytes > 20 * 1024 * 1024)
            throw new ServiceUnavailableException(
              "Photo evidence exceeds the PDF export limit.",
            );
          photo = `<img alt="Activity evidence" src="data:image/jpeg;base64,${bytes.toString("base64")}" />`;
        }
        cards.push(
          `<article><div class="line"><b>${escapeHtml(log.activity_name)}</b><strong>${log.hours_logged.toFixed(2)} hours</strong></div><small>${new Date(log.activity_date).toISOString().slice(0, 10)} · Approved ${cslToday(new Date(log.approved_at))}</small><p>${escapeHtml(log.description)}</p><div class="tags">${log.competency_tags.map((t: string) => `<span>${escapeHtml(t)}</span>`).join("")}</div>${photo}</article>`,
        );
      }
      const logo = data.student.school.logoUrl
        ? await this.photos.schoolLogo(data.student.school.logoUrl)
        : null;
      const html = `<!doctype html><html><head><meta charset="utf-8"><style>@page{size:A4;margin:18mm 16mm}*{box-sizing:border-box}body{font:11px Arial,sans-serif;color:#101820}header{border-bottom:4px solid #BBD125;padding-bottom:16px}h1{font-size:23px;margin:0 0 5px}h2{font-size:18px;margin-top:24px}.muted,small{color:#596778}.details{display:grid;grid-template-columns:1fr 1fr;gap:9px;background:#f5f7f8;padding:15px;margin:20px 0}.total{font-size:18px;font-weight:bold}.line{display:flex;justify-content:space-between;gap:10px}article{break-inside:avoid;border-bottom:1px solid #dce1e5;padding:15px 0}p{line-height:1.6;white-space:pre-wrap;overflow-wrap:anywhere}.tags span{display:inline-block;background:#f1f5df;border-radius:4px;padding:4px 6px;margin:3px 3px 3px 0}img{display:block;max-width:240px;max-height:150px;margin-top:10px;object-fit:contain}.signature{break-inside:avoid;margin-top:35px;border-top:1px solid #dce1e5;padding-top:18px}.note{font-size:9px;color:#596778;margin-top:18px}</style></head><body><header>${logo ? `<img style="float:right;max-width:65px;max-height:65px;margin:0" alt="School logo" src="${logo}" />` : ""}<h1>${escapeHtml(data.student.school.name)}</h1><div class="muted">${escapeHtml(data.student.school.address ?? "")} · ${escapeHtml(data.student.school.code)}</div></header><h2>Community Service Learning Logbook</h2><div class="details"><div>Student: <b>${escapeHtml(data.student.name)}</b></div><div>Admission: <b>${escapeHtml(data.student.admissionNumber ?? "—")}</b></div><div>Grade: ${escapeHtml(data.student.grade)}</div><div>Stream: ${escapeHtml(data.student.studentProfile?.stream ?? "—")}</div></div><p class="total">Approved service: ${data.hours.toFixed(2)} / ${data.target} hours</p><p class="muted">Approved activities only · ${data.logs.length} entries</p>${cards.join("")}<section class="signature"><b>CSL Coordinator</b><p>Name: __________________________________________</p><p>Signature: __________________________ Date: __________________</p><p>School stamp: ___________________________________</p></section><p class="note">Generated by Assignment Hub. School tracking target; this is not an official KICD certification or confirmation of examination eligibility. Research-project completion is verified separately.</p></body></html>`;
      browser = await puppeteer.launch({
        executablePath:
          this.config.get<string>("CSL_CHROMIUM_EXECUTABLE") ||
          (await chromium.executablePath()),
        args: chromium.args,
        headless: true,
        timeout: 30000,
      });
      const page = await browser.newPage();
      await page.setJavaScriptEnabled(false);
      await page.setRequestInterception(true);
      page.on("request", (r) =>
        r.url().startsWith("data:") ? r.continue() : r.abort(),
      );
      await page.setContent(html, { waitUntil: "load", timeout: 30000 });
      return Buffer.from(
        await page.pdf({
          format: "A4",
          printBackground: true,
          displayHeaderFooter: true,
          headerTemplate: "<span></span>",
          footerTemplate:
            '<div style="font:8px Arial;width:100%;text-align:center;color:#596778">Assignment Hub · Page <span class="pageNumber"></span> of <span class="totalPages"></span></div>',
          timeout: 30000,
        }),
      );
    } finally {
      if (browser) await browser.close().catch(() => {});
      this.busy = false;
    }
  }
}
